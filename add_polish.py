import os, glob, re

base = "D:/WZJ/摸鱼：他们都以为我只是个写小说的/content"
cn = {'零':0,'一':1,'二':2,'两':2,'三':3,'四':4,'五':5,'六':6,
      '七':7,'八':8,'九':9,'十':10,'百':100,'千':1000}
def cn2int(s):
    t=0; c=0
    for ch in s:
        if ch in ('十','百','千'):
            u = cn[ch]
            if u == 10:
                c = c if c else 1; t += c*10; c = 0
            elif u == 100:
                t += c*100; c = 0
            elif u == 1000:
                t += c*1000; c = 0
        else:
            c = cn.get(ch, 0)
    return t + c

