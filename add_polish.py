for ch, txt in additions.items():
    p = files[ch]
    s = open(p, encoding='utf-8').read()
    lines = s.split('\n')
    idx = None
    for i in range(len(lines)-1, -1, -1):
        if re.match(r'——（第.+?章 完）——', lines[i].strip()):
            idx = i
            break
    if idx is None:
        print("NO MARKER", ch)
        continue
    lines.insert(idx, '\n' + txt)
    open(p, 'w', encoding='utf-8').write('\n'.join(lines))
    print("added", ch)

